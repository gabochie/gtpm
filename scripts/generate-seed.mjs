#!/usr/bin/env node
// ============================================================
// GTPM seed generator
// Reads seed/data/*.json → emits seed/seed.sql
// Deterministic UUIDs (hash of name) so reseeding is stable.
// Later files override earlier ones for duplicate org names:
//   fallback.json first, then agent-*.json (verified research wins).
// ============================================================
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_DIR = join(__dirname, 'data');
const OUT = join(__dirname, '..', 'seed', 'seed.sql');

// ---------- deterministic id ----------
function hashId(seed) {
  const mix = (a, b) => {
    let h1 = a, h2 = b;
    for (let i = 0; i < seed.length; i++) {
      const ch = seed.charCodeAt(i);
      h1 = Math.imul(h1 ^ ch, 2654435761);
      h2 = Math.imul(h2 ^ ch, 1597334677);
    }
    h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
    h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
    return (h1 >>> 0).toString(16).padStart(8, '0') + (h2 >>> 0).toString(16).padStart(8, '0');
  };
  // two passes with different salts → 32 hex chars → valid UUID shape
  const n = mix(0xdeadbeef, 0x41c6ce57) + mix(0x9e3779b9, 0x85ebca6b);
  return `${n.slice(0, 8)}-${n.slice(8, 12)}-4${n.slice(13, 16)}-a${n.slice(17, 20)}-${n.slice(20, 32)}`;
}
const id = (s) => hashId(`gtpm:${s.toLowerCase().trim()}`);

// ---------- helpers ----------
const esc = (v) => {
  if (v == null) return 'NULL';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const json = (v) => (v == null ? 'NULL' : `'${JSON.stringify(v).replace(/'/g, "''")}'`);
const lines = [];
const add = (sql) => lines.push(sql);

const slugify = (s) =>
  String(s).toLowerCase().trim().replace(/[^a-z0-9\s-]/g, '').replace(/[\s_]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '');

// ---------- load data ----------
const files = readdirSync(DATA_DIR).filter((f) => f.endsWith('.json'));
// fallback first, then agent-* (later wins), taxonomy/demo always applied
const order = [
  'fallback.json',
  ...files.filter((f) => f.startsWith('agent-')).sort(),
];
const orgFiles = order.filter((f) => existsSync(join(DATA_DIR, f)));
const taxFile = files.find((f) => f === 'taxonomy.json');
const demoFile = files.find((f) => f === 'demo-content.json');

const taxonomy = taxFile ? JSON.parse(readFileSync(join(DATA_DIR, taxFile), 'utf8')) : { sectors: [], locations: [], technologies: [] };
const demo = demoFile ? JSON.parse(readFileSync(join(DATA_DIR, demoFile), 'utf8')) : { signals: [], opportunities: [], regulations: [], events: [], reports: [], news: [] };

// merge organizations (later wins)
const orgByName = new Map();
for (const f of orgFiles) {
  const data = JSON.parse(readFileSync(join(DATA_DIR, f), 'utf8'));
  for (const org of data.organizations ?? []) {
    orgByName.set(org.name.toLowerCase().trim(), org);
  }
}
const orgs = [...orgByName.values()];

// ---------- emit ----------
add('-- GTPM seed (generated by scripts/generate-seed.mjs — do not edit)');
add('PRAGMA foreign_keys = ON;');
add('BEGIN;');

// sectors
for (const s of taxonomy.sectors) {
  add(`INSERT OR REPLACE INTO sectors (id, slug, name, description, sort_order) VALUES (${esc(id(`sector:${s.slug}`))}, ${esc(s.slug)}, ${esc(s.name)}, ${esc(s.description ?? null)}, ${esc(s.sort_order ?? 0)});`);
}
// locations (respect parent linkage)
const locParent = (loc) => {
  const parent = taxonomy.locations.find((l) => l.slug === loc.parent);
  return parent ? id(`location:${parent.slug}`) : null;
};
for (const l of taxonomy.locations) {
  add(`INSERT OR REPLACE INTO locations (id, slug, name, type, parent_id, country_code, lat, lng, is_capital) VALUES (${esc(id(`location:${l.slug}`))}, ${esc(l.slug)}, ${esc(l.name)}, ${esc(l.type)}, ${esc(locParent(l))}, ${esc(l.country_code)}, ${esc(l.lat ?? null)}, ${esc(l.lng ?? null)}, ${esc(l.is_capital ?? 0)});`);
}
// technologies
for (const t of taxonomy.technologies) {
  add(`INSERT OR REPLACE INTO technologies (id, slug, name, description, lifecycle, radar_ring, trend_score) VALUES (${esc(id(`tech:${t.slug}`))}, ${esc(t.slug)}, ${esc(t.name)}, ${esc(t.description ?? null)}, ${esc(t.lifecycle ?? 'emerging')}, ${esc(t.radar_ring ?? 'EMERGING')}, ${esc(t.trend_score ?? null)});`);
}

// sources (from orgs)
const sourceSeen = new Set();
// schema enum: official, government, ecosystem, news, social, research, database, regulator
const SOURCE_TYPE_MAP = { corporate: 'official', media: 'news', ngo: 'ecosystem', blog: 'news', report: 'research', database: 'database' };
const ensureSource = (src) => {
  if (!src?.url) return null;
  const sid = id(`source:${src.url}`);
  if (!sourceSeen.has(sid)) {
    sourceSeen.add(sid);
    const st = SOURCE_TYPE_MAP[src.source_type] ?? src.source_type ?? 'news';
    add(`INSERT OR REPLACE INTO sources (id, url, title, publisher, source_type, reliability, fetch_frequency) VALUES (${esc(sid)}, ${esc(src.url)}, ${esc(src.title ?? src.url)}, ${esc(src.publisher ?? null)}, ${esc(st)}, ${esc(src.reliability ?? 0.5)}, 'monthly');`);
  }
  return sid;
};

// organizations + joined rows
for (const o of orgs) {
  const oid = id(`org:${o.name}`);
  const loc = taxonomy.locations.find((l) => l.slug === slugify(o.hq_city ?? ''));
  const locId = loc ? id(`location:${loc.slug}`) : null;
  const srcIds = (o.sources ?? []).map((s) => ensureSource(s)).filter(Boolean);

  add(`INSERT OR REPLACE INTO organizations (id, slug, name, legal_name, org_type, description, overview, founded_year, hq_location_id, website, socials, email, employee_count, funding_status, status, verification_status, confidence, monitor_frequency, is_private, is_seed) VALUES (${esc(oid)}, ${esc(slugify(o.name))}, ${esc(o.name)}, ${esc(o.legal_name ?? null)}, ${esc(o.org_type ?? 'startup')}, ${esc(o.description ?? null)}, ${esc(o.overview ?? null)}, ${esc(o.founded_year ?? null)}, ${esc(locId)}, ${esc(o.website ?? null)}, ${json(o.socials ?? {})}, ${esc(o.email ?? null)}, ${esc(o.employee_count ?? null)}, ${esc(o.funding_status ?? null)}, ${esc(o.status ?? 'active')}, ${esc(o.verification_status ?? 'reported')}, ${esc(o.confidence ?? 0.5)}, ${esc(o.monitor_frequency ?? 'weekly')}, ${esc(o.is_private ?? 0)}, ${esc(o.is_seed ?? 0)});`);

  // sectors
  for (const s of o.sectors ?? []) {
    const tax = taxonomy.sectors.find((t) => t.name.toLowerCase() === String(s).toLowerCase() || t.slug === slugify(s));
    if (tax) {
      add(`INSERT OR IGNORE INTO organization_sectors (organization_id, sector_id, is_primary) VALUES (${esc(oid)}, ${esc(id(`sector:${tax.slug}`))}, 0);`);
    }
  }
  // technologies
  for (const t of o.technologies ?? []) {
    const tax = taxonomy.technologies.find((x) => x.name.toLowerCase() === String(t.name).toLowerCase() || x.slug === slugify(t.name));
    if (tax) {
      add(`INSERT OR IGNORE INTO organization_technologies (organization_id, technology_id, adoption_level) VALUES (${esc(oid)}, ${esc(id(`tech:${tax.slug}`))}, ${esc(t.adoption ?? 'exploring')});`);
    }
  }
  // people
  for (const p of o.people ?? []) {
    const pid = id(`person:${p.name}`);
    add(`INSERT OR REPLACE INTO people (id, slug, name, role, title, verification_status, confidence) VALUES (${esc(pid)}, ${esc(slugify(p.name))}, ${esc(p.name)}, ${esc(p.role ?? 'executive')}, ${esc(p.title ?? null)}, 'reported', 0.6);`);
    add(`INSERT OR REPLACE INTO organization_people (organization_id, person_id, role, title, is_founder, is_current) VALUES (${esc(oid)}, ${esc(pid)}, ${esc(p.title ?? p.role ?? null)}, ${esc(p.title ?? null)}, ${esc(p.is_founder ? 1 : 0)}, 1);`);
  }
  // products
  for (const pr of o.products ?? []) {
    const prid = id(`product:${o.name}:${pr.name}`);
    add(`INSERT OR REPLACE INTO products (id, slug, organization_id, name, description, category, technology, status, url) VALUES (${esc(prid)}, ${esc(slugify(pr.name))}, ${esc(oid)}, ${esc(pr.name)}, ${esc(pr.description ?? null)}, ${esc(pr.category ?? null)}, ${json([])}, 'active', ${esc(pr.url ?? null)});`);
  }
  // funding rounds
  for (const f of o.funding ?? []) {
    const fid = id(`funding:${o.name}:${f.date ?? 'unknown'}:${f.round_type ?? 'unknown'}`);
    const investorNames = (f.investors ?? []).map((i) => (typeof i === 'string' ? i : i.name));
    add(`INSERT OR REPLACE INTO funding_rounds (id, organization_id, round_type, amount_usd, date, date_precision, investors, lead_investor, confidence) VALUES (${esc(fid)}, ${esc(oid)}, ${esc(f.round_type ?? 'unknown')}, ${esc(f.amount_usd ?? null)}, ${esc(f.date ?? null)}, 'month', ${json(investorNames.map((n) => ({ name: n })))}, ${esc(f.lead_investor ?? investorNames[0] ?? null)}, ${esc(f.confidence ?? 0.7)});`);
  }
}

// ---------- org-to-org links (second pass: all org rows exist now) ----------
for (const o of orgs) {
  const oid = id(`org:${o.name}`);
  // competitors (org-to-org)
  for (const c of o.competitors ?? []) {
    const co = orgByName.get(String(c.name).toLowerCase().trim());
    if (co && co.name.toLowerCase().trim() !== o.name.toLowerCase().trim()) {
      const coid = id(`org:${co.name}`);
      add(`INSERT OR REPLACE INTO competitors (id, organization_id, competitor_org_id, competition_type, strength) VALUES (${esc(id(`comp:${o.name}:${co.name}:${c.competition_type ?? 'direct'}`))}, ${esc(oid)}, ${esc(coid)}, ${esc(c.competition_type ?? 'direct')}, 0.5);`);
    }
  }
  // partnerships (org-to-org)
  for (const p of o.partnerships ?? []) {
    const partner = orgByName.get(String(p.org_b).toLowerCase().trim());
    if (partner && partner.name.toLowerCase().trim() !== o.name.toLowerCase().trim()) {
      add(`INSERT OR REPLACE INTO partnerships (id, org_a_id, org_b_id, partnership_type, description, status) VALUES (${esc(id(`part:${o.name}:${p.org_b}`))}, ${esc(oid)}, ${esc(id(`org:${partner.name}`))}, ${esc(p.partnership_type ?? 'strategic')}, ${esc(p.description ?? null)}, 'active');`);
    }
  }
}

// ---------- demo intelligence content ----------
for (const e of demo.events ?? []) {
  const org = orgByName.get(String(e.org ?? '').toLowerCase().trim());
  if (!org) continue;
  const eid = id(`event:${e.title}`);
  add(`INSERT OR REPLACE INTO events (id, organization_id, event_type, title, description, date, date_precision, importance) VALUES (${esc(eid)}, ${esc(id(`org:${org.name}`))}, ${esc(e.event_type ?? 'product')}, ${esc(e.title)}, ${esc(e.description ?? null)}, ${esc(e.date ?? null)}, ${esc(e.date_precision ?? 'month')}, ${esc(e.importance ?? 'signal')});`);
}
for (const s of demo.signals ?? []) {
  const org = orgByName.get(String(s.org ?? '').toLowerCase().trim());
  if (!org) continue;
  const sid = id(`signal:${s.title}`);
  add(`INSERT OR REPLACE INTO signals (id, organization_id, signal_type, title, description, importance, date, strategic_interpretation, metadata) VALUES (${esc(sid)}, ${esc(id(`org:${org.name}`))}, ${esc(s.signal_type ?? 'tech_adoption')}, ${esc(s.title)}, ${esc(s.description ?? null)}, ${esc(s.importance ?? 'signal')}, ${esc(s.date ?? new Date().toISOString().slice(0, 10))}, ${esc(s.strategic_interpretation ?? null)}, ${json({ demo: true })});`);
}
for (const o of demo.opportunities ?? []) {
  const sec = taxonomy.sectors.find((t) => t.slug === slugify(o.sector ?? ''));
  const oid = id(`opp:${o.title}`);
  add(`INSERT OR REPLACE INTO opportunities (id, slug, title, problem, market, sector_id, existing_alternatives, current_competitors, why_now, technology_required, barriers, potential_customers, business_model, attractiveness, classification, evidence, confidence, status) VALUES (${esc(oid)}, ${esc(slugify(o.title))}, ${esc(o.title)}, ${esc(o.problem ?? null)}, ${esc(o.market ?? null)}, ${esc(sec ? id(`sector:${sec.slug}`) : null)}, ${json(o.existing_alternatives ?? [])}, ${json(o.current_competitors ?? [])}, ${esc(o.why_now ?? null)}, ${json(o.technology_required ?? [])}, ${json(o.barriers ?? [])}, ${esc(o.potential_customers ?? null)}, ${esc(o.business_model ?? null)}, ${esc(o.attractiveness ?? 0.5)}, ${esc(o.classification ?? 'WATCH')}, ${json(o.evidence ?? [])}, ${esc(o.confidence ?? 0.4)}, 'open');`);
}
for (const r of demo.regulations ?? []) {
  add(`INSERT OR REPLACE INTO regulations (id, slug, title, body, agency, jurisdiction, sector_ids, status, published_date, effective_date) VALUES (${esc(id(`reg:${r.title}`))}, ${esc(slugify(r.title))}, ${esc(r.title)}, ${esc(r.body ?? null)}, ${esc(r.agency ?? null)}, 'GH', ${json(r.sector_ids ?? [])}, ${esc(r.status ?? 'in_force')}, ${esc(r.published_date ?? null)}, ${esc(r.effective_date ?? null)});`);
}
for (const rep of demo.reports ?? []) {
  add(`INSERT OR REPLACE INTO reports (id, slug, title, report_type, content, status, generated_at) VALUES (${esc(id(`report:${rep.title}`))}, ${esc(slugify(rep.title))}, ${esc(rep.title)}, ${esc(rep.report_type ?? 'custom')}, ${json(rep.content ?? {})}, ${esc(rep.status ?? 'draft')}, ${esc(rep.generated_at ?? null)});`);
}
for (const n of demo.news ?? []) {
  const sid = ensureSource({ url: n.url, title: n.title, publisher: n.publisher, source_type: 'news', reliability: 0.7 });
  add(`INSERT OR REPLACE INTO news_items (id, title, url, publisher, published_date, summary, org_ids, sector_ids, source_id) VALUES (${esc(id(`news:${n.title}`))}, ${esc(n.title)}, ${esc(n.url ?? null)}, ${esc(n.publisher ?? null)}, ${esc(n.published_date ?? null)}, ${esc(n.summary ?? null)}, ${json(n.org_ids ?? [])}, ${json(n.sector_ids ?? [])}, ${esc(sid)});`);
}

add('COMMIT;');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lines.join('\n') + '\n');
console.log(`✅ seed.sql generated: ${orgs.length} organizations, ${taxonomy.sectors.length} sectors, ${taxonomy.locations.length} locations, ${taxonomy.technologies.length} technologies, ${demo.events.length} events, ${demo.signals.length} signals, ${demo.opportunities.length} opportunities, ${demo.regulations.length} regulations, ${demo.reports.length} reports`);
