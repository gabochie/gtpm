/* GTPM — company profile (the intelligence dossier) */
(async () => {
  const { $, esc, money, fmtDate, timeAgo, typeLabel, typeClass, impBadge, verifBadge, conf, loader, empty } = UI;
  const root = $('#root');
  const slug = new URLSearchParams(location.search).get('slug');
  if (!slug) { root.innerHTML = empty('No organisation specified.'); return; }

  const SCORE_LABELS = {
    technology_strength: 'Technology strength', market_position: 'Market position',
    growth_momentum: 'Growth momentum', funding_strength: 'Funding strength',
    talent_strength: 'Talent strength', product_strength: 'Product strength',
    ecosystem_influence: 'Ecosystem influence', innovation_velocity: 'Innovation velocity',
    strategic_threat: 'Strategic threat',
  };
  const EVENT_ICON = { launch: '🚀', funding: '💰', partnership: '🤝', acquisition: '🤝', regulatory: '⚖', leadership: '👤', product: '🛠', expansion: '↗', hiring: '👥' };

  let org;
  try {
    org = await API.company(slug);
  } catch (e) { root.innerHTML = ''; UI.errorBanner(e, root); root.insertAdjacentHTML('beforeend', empty('Organisation not found.')); return; }
  document.title = `${org.name} — GTPM`;

  const head = `
    <div class="profile-head">
      <div class="ph-main">
        <div class="eyebrow" style="margin-bottom:8px">Organisation dossier</div>
        <h1>${esc(org.name)}</h1>
        <div class="ph-sub">${esc(org.description ?? '')}</div>
        <div class="ph-chips">
          <span class="org-type" style="font-family:var(--font-mono);font-size:10px;text-transform:uppercase;letter-spacing:.1em;color:var(--text-3);border:1px solid var(--border);padding:3px 8px;border-radius:4px">${esc(typeLabel(org.org_type))}</span>
          ${org.sectors.map((s) => `<a class="chip" href="sectors.html?slug=${esc(s.slug)}">${esc(s.name)}</a>`).join('')}
          ${verifBadge(org.verification_status)}
          ${conf(org.confidence)}
        </div>
        <div class="ph-chips">
          ${org.website ? `<a class="chip green" href="${esc(org.website)}" target="_blank" rel="noopener">↗ website</a>` : ''}
          ${org.hq_location ? `<span class="chip">📍 ${esc(org.hq_location.name)}</span>` : ''}
          ${org.funding_status ? `<span class="chip gold">${esc(org.funding_status.replace(/_/g, ' '))}</span>` : ''}
          ${org.is_seed ? '<span class="chip">★ seed portfolio</span>' : ''}
          <span id="follow-slot"></span>
        </div>
      </div>
    </div>
    <div class="profile-meta">
      <div class="pm"><div class="pm-label">Founded</div><div class="pm-val">${org.founded_year ?? '—'}</div></div>
      <div class="pm"><div class="pm-label">Headquarters</div><div class="pm-val">${esc(org.hq_location?.name ?? '—')}</div></div>
      <div class="pm"><div class="pm-label">Monitor cadence</div><div class="pm-val">${esc(org.monitor_frequency)}</div></div>
      <div class="pm"><div class="pm-label">Last checked</div><div class="pm-val">${org.last_checked ? timeAgo(org.last_checked) : 'pending'}</div></div>
      <div class="pm"><div class="pm-label">Total tracked funding</div><div class="pm-val">${money(org.total_funding_usd)}</div></div>
      <div class="pm"><div class="pm-label">Funding rounds</div><div class="pm-val">${org.funding.length}</div></div>
    </div>`;

  const scores = `
    <section style="margin-top:24px">
      <div class="sec-head" style="margin-bottom:14px"><div><span class="sec-kicker">Scored dimensions</span><h2>Competitive assessment</h2></div></div>
      ${org.scores.length ? `<div class="score-grid">
        ${org.scores.map((s) => `
          <div class="score-cell">
            <div class="sc-label">${esc(SCORE_LABELS[s.dimension] ?? s.dimension.replace(/_/g, ' '))}</div>
            <div class="sc-val">${Math.round(s.score)}</div>
            <div class="sc-meter"><i style="width:${s.score}%"></i></div>
            <div class="sc-conf">confidence ${Math.round(s.confidence * 100)}%</div>
          </div>`).join('')}
      </div>` : `<div class="card"><p class="muted small">Scores are generated by the scoring pipeline as intelligence accumulates. ${org.name} is still being scored.</p></div>`}
    </section>`;

  const overview = `
    <section class="card" style="margin-top:24px">
      <div class="sec-kicker" style="margin-bottom:6px">Editorial overview</div>
      <p style="color:var(--text-2);line-height:1.7;font-size:14px">${esc(org.overview ?? org.description ?? 'No overview yet.')}</p>
    </section>`;

  const products = `
    <section style="margin-top:24px">
      <div class="sec-head" style="margin-bottom:14px"><div><span class="sec-kicker">Product surface</span><h2>Products</h2></div></div>
      ${org.products.length ? `<div class="grid grid-2">
        ${org.products.map((p) => `
          <div class="card tight">
            <div style="display:flex;justify-content:space-between;gap:8px">
              <div class="card-title" style="margin:0">${esc(p.name)}</div>
              ${p.category ? `<span class="chip">${esc(p.category)}</span>` : ''}
            </div>
            ${p.description ? `<p class="card-sub" style="margin-top:6px">${esc(p.description)}</p>` : ''}
            ${p.url ? `<a class="src-link" href="${esc(p.url)}" target="_blank" rel="noopener">${esc(p.url)} ↗</a>` : ''}
          </div>`).join('')}
      </div>` : empty('No products tracked yet.')}
    </section>`;

  const timeline = `
    <section style="margin-top:24px">
      <div class="sec-head" style="margin-bottom:14px"><div><span class="sec-kicker">History</span><h2>Timeline</h2></div></div>
      <div class="card">
      ${org.timeline.length ? `<div class="timeline">
        ${org.timeline.slice(0, 25).map((t) => `
          <div class="tl-item ${t.importance}">
            <div class="tl-date">${fmtDate(t.date)} · ${esc(t.type)}</div>
            <div class="tl-title">${EVENT_ICON[t.type] ?? '▸'} ${esc(t.title)}</div>
            ${t.description ? `<div class="tl-desc">${esc(t.description)}</div>` : ''}
          </div>`).join('')}
      </div>` : empty('No timeline events yet.')}
      </div>
    </section>`;

  const fundingSide = `
    <section class="card">
      <div class="sec-kicker" style="margin-bottom:8px">Capital</div>
      <div style="font-family:var(--font-mono);font-size:26px;font-weight:600">${money(org.total_funding_usd)}</div>
      <div class="small muted" style="margin-top:2px">total tracked · ${org.funding.length} rounds</div>
      ${org.funding.length ? `<div class="flow" style="margin-top:14px">
        ${org.funding.map((f) => `
          <div style="border-top:1px solid var(--border);padding-top:10px">
            <div style="display:flex;justify-content:space-between;align-items:center">
              <span class="chip gold">${esc(f.round_type.replace(/_/g, ' '))}</span>
              <span class="mono small muted">${fmtDate(f.date)}</span>
            </div>
            <div style="font-family:var(--font-mono);font-size:15px;margin-top:6px">${money(f.amount_usd)}</div>
            ${f.investors?.length ? `<div class="pill-row" style="margin-top:6px">${f.investors.map((i) => `<span class="chip">${esc(i.name)}</span>`).join('')}</div>` : ''}
          </div>`).join('')}
      </div>` : '<p class="muted small" style="margin-top:10px">No public funding rounds tracked yet.</p>'}
    </section>`;

  const competitors = `
    <section class="card">
      <div class="sec-kicker" style="margin-bottom:8px">Competition</div>
      ${org.competitors.length ? `<div class="flow">
        ${org.competitors.map((cmp) => `
          <div style="display:flex;align-items:center;justify-content:space-between;gap:8px;border-top:1px solid var(--border);padding-top:10px">
            <div>
              <a href="company.html?slug=${esc(cmp.competitor.slug)}" style="font-weight:600;font-size:13.5px">${esc(cmp.competitor.name)}</a>
              <div class="small muted">${esc(cmp.competition_type.replace(/_/g, ' '))}</div>
            </div>
            <span class="chip ${cmp.competition_type === 'direct' ? 'red' : cmp.competition_type === 'global' ? 'blue' : 'gold'}">${cmp.competition_type}</span>
          </div>`).join('')}
      </div>` : empty('No competitors mapped yet.')}
    </section>`;

  const partners = `
    <section class="card">
      <div class="sec-kicker" style="margin-bottom:8px">Partnerships</div>
      ${org.partnerships.length ? `<div class="flow">
        ${org.partnerships.map((p) => `
          <div style="display:flex;align-items:center;gap:10px;border-top:1px solid var(--border);padding-top:10px">
            <span class="chip green">⇄</span>
            <div>
              <a href="company.html?slug=${esc(p.partner.slug)}" style="font-weight:600;font-size:13.5px">${esc(p.partner.name)}</a>
              <div class="small muted">${esc(p.partnership_type.replace(/_/g, ' '))}</div>
            </div>
          </div>`).join('')}
      </div>` : empty('No partnerships tracked yet.')}
    </section>`;

  const people = `
    <section class="card">
      <div class="sec-kicker" style="margin-bottom:8px">Leadership</div>
      ${org.people.length ? `<div class="flow">
        ${org.people.map((p) => `
          <div style="display:flex;align-items:center;gap:10px;border-top:1px solid var(--border);padding-top:10px">
            <span style="width:30px;height:30px;border-radius:50%;background:var(--panel-2);display:grid;place-items:center;font-size:12px;font-weight:600;flex-shrink:0">${esc((p.name || '?').split(' ').map((x) => x[0]).slice(0, 2).join(''))}</span>
            <div>
              <div style="font-weight:600;font-size:13.5px">${esc(p.name)} ${p.is_founder ? '<span class="chip gold" style="font-size:9.5px">founder</span>' : ''}</div>
              <div class="small muted">${esc(p.title ?? '')}</div>
            </div>
          </div>`).join('')}
      </div>` : empty('No leadership tracked yet.')}
    </section>`;

  const sources = `
    <section class="card">
      <div class="sec-kicker" style="margin-bottom:8px">Provenance</div>
      <p class="small muted" style="margin-bottom:10px">Key claims on this profile trace to these sources.</p>
      ${org.sources.length ? `<div class="flow">
        ${org.sources.map((s) => `
          <div style="border-top:1px solid var(--border);padding-top:8px">
            ${s.url ? `<a class="src-link" href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.title)} ↗</a>` : `<span class="src-link">${esc(s.title)}</span>`}
            <div class="small muted">${esc(s.publisher ?? '')} · reliability ${Math.round(s.reliability * 100)}% · ${esc(s.source_type)}</div>
          </div>`).join('')}
      </div>` : empty('No sources linked yet.')}
    </section>`;

  const signals = `
    <section style="margin-top:24px">
      <div class="sec-head" style="margin-bottom:14px"><div><span class="sec-kicker">Signals</span><h2>Why ${esc(org.name)} matters</h2></div></div>
      ${org.signals.length ? org.signals.slice(0, 6).map((x) => `
        <div class="signal-item">
          <div class="sig-ico">◈</div>
          <div class="sig-body">
            <div class="sig-title">${esc(x.title)}</div>
            ${x.description ? `<div class="sig-desc">${esc(x.description)}</div>` : ''}
            ${x.strategic_interpretation ? `<div class="sig-why">${esc(x.strategic_interpretation)}</div>` : ''}
            <div class="sig-meta">${impBadge(x.importance)}<span class="mono small muted">${timeAgo(x.date)}</span></div>
          </div>
        </div>`).join('') : empty('No signals captured yet.')}
    </section>`;

  root.innerHTML = head + scores + overview +
    `<div class="two-col-detail" style="margin-top:24px">
      <div>${timeline}${signals}${products}</div>
      <div class="flow" style="display:grid;gap:16px">${fundingSide}${competitors}${partners}${people}${sources}</div>
    </div>`;
  const followSlot = $('#follow-slot');
  if (followSlot) followSlot.replaceWith(UI.followButton('organization', org.id, org.name));
})();
